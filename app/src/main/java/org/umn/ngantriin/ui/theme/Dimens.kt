package org.umn.ngantriin.ui.theme

import androidx.compose.ui.unit.dp

/** Spacing scale. Everything in the UI is a multiple of 4dp. */
object Spacing {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 20.dp
    val xxl = 24.dp
    val xxxl = 32.dp
    val huge = 48.dp

    /** Horizontal gutter used by every full-width screen. */
    val screenGutter = 20.dp

    /** Minimum touch target (section 42). */
    val touchTarget = 48.dp
}
